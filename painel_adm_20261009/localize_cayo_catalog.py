CONTEXT={'air':'Aeroporto','bch':'Praia','dock':'Porto','islp':'Ilha','man':'Mansão','manb':'Mansão','manl':'Mansão','wtow':'Interior da ilha','wtowers':'Interior da ilha'}
def label(model):
    tokens=re.findall('[a-z]+',model)
    context=next((CONTEXT[t] for t in tokens if t in CONTEXT),None)
    words=[]
    for t in tokens:
        if t in IGNORE or t in CONTEXT or len(t)==1: continue
        assert t in WORDS, f'Untranslated model token: {t} ({model})'
        if not words or words[-1]!=WORDS[t]: words.append(WORDS[t])
    assert words,model
    return ' · '.join(words)+(f' ({context})' if context else '')
def main():
    catalog=json.loads(CAT.read_text(encoding='utf8'))
    groups=collections.defaultdict(list)
    for row in catalog['objects']: groups[label(row['sourceModel'])].append(row)
    names={}
    for name,rows in groups.items():
        for index,row in enumerate(sorted(rows,key=lambda r:r['sourceModel']),1):
            row['name']=name+(f' — variação {index:02}' if len(rows)>1 else '')
            names[row['sourceModel']]=row['name']
    (ROOT/'cayo_names_pt_br.json').write_text(json.dumps(names,ensure_ascii=False,indent=2),encoding='utf8')
    catalog['revision']='editor-ptbr-controles-20261010-1'
    CAT.write_text(json.dumps(catalog,ensure_ascii=False,indent=2),encoding='utf8')
    print('PORTUGUESE_NAMES',len(names))
if __name__=='__main__': main()
